TONES = ["Neutral", "Success", "Warning", "Danger", "Info"]

def tones(on=True):
    out = []
    for t in TONES:
        out.append(f'        <Style Selector="^[Tone={t}]">\n            <Setter Property="Accent" Value="{{DynamicResource Helix.{t}}}" />')
        if on:
            out.append(f'            <Setter Property="ToneOnBrush" Value="{{DynamicResource Helix.On{t}}}" />')
        out.append('        </Style>')
    return "\n".join(out)

def base_accent(on=True):
    s = '        <Setter Property="Accent" Value="{DynamicResource Helix.Primary}" />'
    if on:
        s += '\n        <Setter Property="ToneOnBrush" Value="{DynamicResource Helix.OnPrimary}" />'
    return s

